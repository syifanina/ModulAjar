// Grouping Question Logic
function setupGroupingInteraction(slideIndex) {
    const container = document.getElementById(`grouping-${slideIndex}`);
    if (!container) return;

    const cards = container.querySelectorAll('.draggable-card');
    const dropTargets = container.querySelectorAll('.drop-target');

    let draggedCard = null;
    let selectedCard = null;
    let initialX, initialY;
    let currentX, currentY;
    let xOffset = 0, yOffset = 0;
    let isDragging = false;
    let wasDragged = false;

    cards.forEach(card => {
        card.addEventListener('mousedown', dragStart);
        card.addEventListener('touchstart', dragStart, {passive: false});
        
        // Handle click explicitly on the card to stop propagation
        card.addEventListener('click', function(e) {
            e.stopPropagation(); // IMPORTANT: stop click from reaching the drop-target
            if (wasDragged) return; // Ignore if we just finished a drag

            if (selectedCard) selectedCard.classList.remove('selected');
            
            if (selectedCard === this) {
                selectedCard = null; // Toggle off
            } else {
                selectedCard = this;
                selectedCard.classList.add('selected');
            }
        });
    });

    dropTargets.forEach(target => {
        target.addEventListener('click', function(e) {
            if (selectedCard) {
                this.appendChild(selectedCard);
                selectedCard.classList.remove('selected');
                selectedCard = null;
            }
        });
    });

    function dragStart(e) {
        if (e.target.classList.contains('draggable-card')) {
            isDragging = false;
            wasDragged = false;

            if (e.type === 'touchstart') {
                initialX = e.touches[0].clientX - xOffset;
                initialY = e.touches[0].clientY - yOffset;
            } else {
                initialX = e.clientX - xOffset;
                initialY = e.clientY - yOffset;
            }

            draggedCard = e.target;
            
            if (e.type === 'touchstart') {
                document.addEventListener('touchmove', drag, {passive: false});
                document.addEventListener('touchend', dragEnd);
            } else {
                document.addEventListener('mousemove', drag);
                document.addEventListener('mouseup', dragEnd);
            }
        }
    }

    function drag(e) {
        if (!draggedCard) return;

        // Determine distance moved to differentiate tap from drag
        const pointerX = e.type === 'touchmove' ? e.touches[0].clientX : e.clientX;
        const pointerY = e.type === 'touchmove' ? e.touches[0].clientY : e.clientY;
        const moveX = pointerX - initialX;
        const moveY = pointerY - initialY;
        
        if (!isDragging && Math.abs(moveX) < 5 && Math.abs(moveY) < 5) {
            return; // Still a tap/click if movement is tiny
        }

        if (!isDragging) {
            isDragging = true;
            wasDragged = true;
            draggedCard.classList.add('dragging');
            const rect = draggedCard.getBoundingClientRect();
            draggedCard.style.width = `${rect.width}px`;
            draggedCard.style.position = 'fixed';
            draggedCard.style.zIndex = 1000;
        }

        e.preventDefault(); 

        if (e.type === 'touchmove') {
            currentX = e.touches[0].clientX - initialX;
            currentY = e.touches[0].clientY - initialY;
        } else {
            currentX = e.clientX - initialX;
            currentY = e.clientY - initialY;
        }

        xOffset = currentX;
        yOffset = currentY;

        draggedCard.style.transform = `translate3d(${currentX}px, ${currentY}px, 0)`;
        
        draggedCard.style.display = 'none';
        const elemBelow = document.elementFromPoint(pointerX, pointerY);
        draggedCard.style.display = 'block';
        
        dropTargets.forEach(t => t.classList.remove('drag-over'));
        if (elemBelow) {
            const target = elemBelow.closest('.drop-target');
            if (target && target.dataset.slideIndex == slideIndex) {
                target.classList.add('drag-over');
            }
        }
    }

    function dragEnd(e) {
        if (!draggedCard) return;
        
        if (isDragging) {
            // Handle Drop
            const x = e.type === 'touchend' ? e.changedTouches[0].clientX : e.clientX;
            const y = e.type === 'touchend' ? e.changedTouches[0].clientY : e.clientY;
            
            draggedCard.style.display = 'none';
            const elemBelow = document.elementFromPoint(x, y);
            draggedCard.style.display = 'block';
            
            let target = null;
            if (elemBelow) {
                target = elemBelow.closest('.drop-target');
            }

            if (target && target.dataset.slideIndex == slideIndex) {
                target.appendChild(draggedCard);
            } else {
                const pool = document.getElementById(`pool-${slideIndex}`);
                if (pool) pool.appendChild(draggedCard);
            }
        }

        // Cleanup
        draggedCard.classList.remove('dragging');
        draggedCard.style.position = '';
        draggedCard.style.zIndex = '';
        draggedCard.style.width = '';
        draggedCard.style.transform = '';
        xOffset = 0;
        yOffset = 0;
        
        dropTargets.forEach(t => t.classList.remove('drag-over'));
        draggedCard = null;
        isDragging = false;
        
        document.removeEventListener('mousemove', drag);
        document.removeEventListener('mouseup', dragEnd);
        document.removeEventListener('touchmove', drag);
        document.removeEventListener('touchend', dragEnd);
    }
}

function checkGrouping(slideIndex) {
    if (slideIndex !== currentSlideIndex || slideStatus[slideIndex] !== 'unanswered') return;

    const q = activeQuizData[slideIndex];
    let isCorrect = true;

    // Must be exactly 4 cards per zone
    q.groups.forEach(group => {
        const zone = document.getElementById(`zone-${slideIndex}-${group.id}`);
        const cardsInZone = Array.from(zone.children).map(c => c.dataset.itemId);
        
        if (cardsInZone.length !== 4) {
            isCorrect = false;
        } else {
            const hasAllCorrect = group.correctItems.every(item => cardsInZone.includes(item));
            if (!hasAllCorrect) isCorrect = false;
        }
    });

    if (!isCorrect) {
        playSound(sfxWarning);
        alert("Coba lagi, periksa kembali ciri-ciri pasar swalayan dan pasar tradisional.");
        return;
    }

    slideStatus[slideIndex] = 'correct';
    playSound(sfxCorrect);
    
    const container = document.getElementById(`grouping-${slideIndex}`);
    const cards = container.querySelectorAll('.draggable-card');
    cards.forEach(card => {
        card.style.pointerEvents = 'none';
        card.style.cursor = 'default';
        card.style.borderColor = '#4CAF50';
        card.style.backgroundColor = '#e8f5e9';
    });
    
    // Hide buttons after correct
    const actions = container.querySelector('.grouping-actions');
    if (actions) actions.style.display = 'none';

    addReviewButton(slideIndex, true, q.explanation);

    alert("Hebat! Jawabanmu benar.");
    updateScoreUI();
    updateUI();
}

function resetGrouping(slideIndex) {
    if (slideStatus[slideIndex] !== 'unanswered') return;

    const pool = document.getElementById(`pool-${slideIndex}`);
    const container = document.getElementById(`grouping-${slideIndex}`);
    const cards = container.querySelectorAll('.draggable-card');
    
    cards.forEach(card => {
        pool.appendChild(card);
    });
}
