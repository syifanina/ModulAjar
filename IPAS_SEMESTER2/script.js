function initQuiz() {
    const lastRange = getQuestionNumRange(activeQuizData.length - 1);
    const maxNum = lastRange.includes('-') ? lastRange.split('-')[1] : lastRange;
    totalSlideNum.innerText = maxNum;
    
    score = 0;
    currentSlideIndex = 0;
    slideStatus = new Array(activeQuizData.length).fill('unanswered');
    multiSelectState = {}; 
    matchingState = {}; // reset matching state
    updateScoreUI();
    renderQuestionNav();
    renderSlides();
    updateUI();
}

function getQuestionNumRange(slideIndex) {
    const q = activeQuizData[slideIndex];
    
    // Check if there is an explicit number at the beginning of the question text
    const match = q.question.match(/^(\d+[A-Z]?)\./);
    if (match) {
        return match[1];
    }
    
    // Fallback: auto-calculate based on slide index and question type
    let currentNum = 1;
    for (let i = 0; i < slideIndex; i++) {
        const prevQ = activeQuizData[i];
        if (prevQ.type === 'matching') {
            currentNum += prevQ.leftItems.length;
        } else {
            currentNum += 1;
        }
    }
    
    if (q.type === 'matching') {
        return `${currentNum}-${currentNum + q.leftItems.length - 1}`;
    }
    return `${currentNum}`;
}

function renderQuestionNav() {
    questionNav.innerHTML = '';
    activeQuizData.forEach((q, index) => {
        const btn = document.createElement('div');
        btn.className = 'nav-number';
        btn.id = `nav-num-${index}`;
        
        const range = getQuestionNumRange(index);
        btn.innerText = range;
        
        if (q.type === 'matching') {
            btn.style.width = 'auto';
            btn.style.padding = '0 10px';
            btn.style.borderRadius = '20px';
        }
        
        btn.onclick = () => goToSlide(index);
        questionNav.appendChild(btn);
    });
}

